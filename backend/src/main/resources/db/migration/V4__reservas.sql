create table reserva (
    id             bigint generated by default as identity primary key,
    lote_id        bigint      not null references lote (id),
    instituicao_id bigint      not null references usuario (id),
    pin            varchar(4)  not null,
    prazo_retirada timestamp with time zone not null,
    status         varchar(20) not null,
    criado_em      timestamp with time zone not null
);

create index idx_reserva_lote on reserva (lote_id);
create index idx_reserva_instituicao on reserva (instituicao_id);
