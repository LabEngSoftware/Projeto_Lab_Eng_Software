alter table usuario add column latitude double precision;
alter table usuario add column longitude double precision;

create table lote (
    id                 bigint generated by default as identity primary key,
    estabelecimento_id bigint         not null references usuario (id),
    nome               varchar(150)   not null,
    categoria          varchar(30)    not null,
    quantidade         numeric(10, 2) not null,
    unidade            varchar(20)    not null,
    preco              numeric(10, 2) not null,
    validade           timestamp with time zone not null,
    retirada_inicio    timestamp with time zone not null,
    retirada_fim       timestamp with time zone not null,
    observacoes        varchar(500),
    endereco_retirada  varchar(255)   not null,
    latitude           double precision not null,
    longitude          double precision not null,
    status             varchar(40)    not null,
    com_foto           boolean        not null,
    criado_em          timestamp with time zone not null
);

-- RNF03: a busca filtra por status e janela de retirada antes de calcular a distância
create index idx_lote_busca on lote (status, retirada_fim);
create index idx_lote_estabelecimento on lote (estabelecimento_id);

create table foto_lote (
    lote_id  bigint primary key references lote (id),
    tipo     varchar(50) not null,
    conteudo bytea       not null
);
