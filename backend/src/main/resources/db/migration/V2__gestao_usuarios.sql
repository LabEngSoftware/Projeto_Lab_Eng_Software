alter table usuario add column score integer not null default 100;
alter table usuario add column token_senha_hash varchar(64);
alter table usuario add column token_senha_expira_em timestamp with time zone;

create table auditoria (
    id          bigint generated by default as identity primary key,
    autor_id    bigint references usuario (id),
    acao        varchar(40)   not null,
    entidade    varchar(40)   not null,
    entidade_id bigint,
    detalhes    varchar(2000),
    criado_em   timestamp with time zone not null
);

create index idx_auditoria_entidade on auditoria (entidade, entidade_id);
